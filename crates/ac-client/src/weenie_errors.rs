//! Text for the server's WeenieError (0x028A) and WeenieErrorWithString
//! (0x028B) codes. The retail client read these from its language DAT;
//! the test server ships none, so the codes are named after ACE's enum
//! identifiers rendered as sentences. `{}` is the string parameter.

/// Message for a WeenieError code, or None for codes with no text.
pub fn text(code: u32) -> Option<&'static str> {
    PLAIN
        .binary_search_by_key(&code, |e| e.0)
        .ok()
        .map(|i| PLAIN[i].1)
}

/// Message for a WeenieErrorWithString code with its parameter filled in.
pub fn text_with(code: u32, param: &str) -> Option<String> {
    WITH.binary_search_by_key(&code, |e| e.0)
        .ok()
        .map(|i| WITH[i].1.replace("{}", param))
}

